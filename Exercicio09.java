package JavaBasico;

public class Exercicio09 {
    public static void main(String[] args) {

        double numeroDecimal = 9.8;
        int numeroInteiro = (int) numeroDecimal;

        System.out.printf("Valor original: %.1f%n", numeroDecimal);
        System.out.printf("Valor convertido para int: %d%n", numeroInteiro);
    }
}
